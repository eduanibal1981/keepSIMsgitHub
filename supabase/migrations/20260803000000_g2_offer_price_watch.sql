-- ---------------------------------------------------------------------------
-- 6. offer_watch_metrics() — current vs baseline for every watchable subject.
--
-- The baseline is the price *as of* the cutoff: for each offer, the last
-- recorded price at or before it, falling back to that offer's first ever
-- sighting when it is younger than the window. That fallback is what makes the
-- feature work on day two instead of day thirty-one — the seed above gives
-- every offer a first sighting today.
--
-- "Current" is read from the live cache, not from the newest history row, so a
-- missed trigger can only under-report a drop, never invent one. The two agree
-- whenever the triggers are healthy.
--
-- eSIM baselines apply TODAY's markup to a historical wholesale price. That
-- deliberately measures supplier movement rather than a markup change: if the
-- business raises ESIM_MARKUP_PERCENT, that is not a price drop to announce,
-- and if it lowers it, announcing a "drop" the supplier did not make would be
-- marketing our own margin back to the user.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.offer_watch_metrics(p_baseline_days integer DEFAULT 30)
RETURNS TABLE (
  source          text,
  country_code    text,
  carrier_code    text,
  metric_kind     text,      -- 'usd_per_gb' (esim) | 'offer_usd' (topup)
  current_metric  numeric,
  baseline_metric numeric,
  drop_percent    numeric,
  offer_label     text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
WITH cfg AS (
  SELECT COALESCE(
           (SELECT NULLIF(sc.config_value, '')::numeric
              FROM public.system_configs sc
             WHERE sc.config_key = 'ESIM_MARKUP_PERCENT'),
           30.0) AS markup,
         NOW() - (GREATEST(COALESCE(p_baseline_days, 30), 1) || ' days')::interval AS cutoff
),
-- ── the price of each offer as of the cutoff ──────────────────────────────
hist_before AS (
  SELECT DISTINCT ON (h.source, h.offer_key) h.*
  FROM public.offer_price_history h, cfg
  WHERE h.recorded_at <= cfg.cutoff
  ORDER BY h.source, h.offer_key, h.recorded_at DESC
),
hist_first AS (
  SELECT DISTINCT ON (h.source, h.offer_key) h.*
  FROM public.offer_price_history h
  ORDER BY h.source, h.offer_key, h.recorded_at ASC
),
baseline AS (
  SELECT * FROM hist_before
  UNION ALL
  SELECT f.* FROM hist_first f
  WHERE NOT EXISTS (
    SELECT 1 FROM hist_before b
    WHERE b.source = f.source AND b.offer_key = f.offer_key
  )
),
-- ── top-ups: per offer, then the biggest drop per (country, carrier) ──────
topup_now AS (
  SELECT p.api_provider || '|' || p.offer_id          AS offer_key,
         p.country_code,
         p.carrier_code,
         COALESCE(p.price_fixed_usd, p.price_min_usd) AS price_usd,
         NULLIF(p.offer_name, '')                     AS offer_name
  FROM public.provider_offers_cache p
  WHERE COALESCE(p.price_fixed_usd, p.price_min_usd) > 0
),
topup_joined AS (
  SELECT n.country_code,
         n.carrier_code,
         n.price_usd  AS current_metric,
         b.price_usd  AS baseline_metric,
         ROUND((b.price_usd - n.price_usd) / b.price_usd * 100.0, 2) AS drop_percent,
         -- The provider gives no offer_name on any live row today, and the raw
         -- offer_id (HUTCH_LK_10-I) is not something to put in front of a user,
         -- so the label leads with the two prices and names the offer only when
         -- there is a real name to use.
         'A top-up that cost $' || to_char(b.price_usd, 'FM99999990.00')
           || ' now costs $' || to_char(n.price_usd, 'FM99999990.00')
           || COALESCE(' (' || n.offer_name || ')', '') AS offer_label
  FROM topup_now n
  JOIN baseline b
    ON b.source = 'topup' AND b.offer_key = n.offer_key
  WHERE b.price_usd > 0
),
topup_best AS (
  SELECT DISTINCT ON (t.country_code, t.carrier_code) t.*
  FROM topup_joined t
  ORDER BY t.country_code, t.carrier_code, t.drop_percent DESC NULLS LAST
),
-- ── eSIM: best retail $/GB per country, now and at the cutoff ─────────────
esim_priced AS (
  SELECT UPPER(u.cc)        AS country_code,
         c.data_amount_mb,
         c.duration_days,
         ROUND(c.wholesale_price_usd * (1.0 + (SELECT markup FROM cfg) / 100.0), 2) AS retail_usd,
         ROUND(ROUND(c.wholesale_price_usd * (1.0 + (SELECT markup FROM cfg) / 100.0), 2)
               / (c.data_amount_mb / 1024.0), 4) AS usd_per_gb
  FROM public.esim_offers_cache c
  CROSS JOIN LATERAL UNNEST(c.countries) AS u(cc)
  WHERE c.is_active = true
    AND c.data_amount_mb > 0
    AND c.wholesale_price_usd > 0
),
esim_now AS (
  SELECT DISTINCT ON (e.country_code) e.*
  FROM esim_priced e
  ORDER BY e.country_code, e.usd_per_gb ASC
),
esim_base AS (
  SELECT UPPER(u.cc) AS country_code,
         MIN(ROUND(ROUND(b.price_usd * (1.0 + (SELECT markup FROM cfg) / 100.0), 2)
                   / (b.data_amount_mb / 1024.0), 4)) AS usd_per_gb
  FROM baseline b
  CROSS JOIN LATERAL UNNEST(b.countries) AS u(cc)
  WHERE b.source = 'esim'
    AND b.data_amount_mb > 0
    AND b.price_usd > 0
  GROUP BY 1
)
SELECT 'topup'::text,
       t.country_code,
       t.carrier_code,
       'offer_usd'::text,
       t.current_metric,
       t.baseline_metric,
       t.drop_percent,
       t.offer_label
FROM topup_best t
UNION ALL
SELECT 'esim'::text,
       n.country_code,
       NULL::text,
       'usd_per_gb'::text,
       n.usd_per_gb,
       b.usd_per_gb,
       ROUND((b.usd_per_gb - n.usd_per_gb) / b.usd_per_gb * 100.0, 2),
       -- Same rule as EsimPlan.formattedData: MB below 1024, GB above, and an
       -- integer when it divides evenly. The app's plan card shows "1000 MB"
       -- with "$1.63 /GB" beside it, so a notification saying "1.0 GB" would
       -- read as an arithmetic error against a $/GB computed from 1024.
       -- NB 'FM999990.9' would render 1000 MB as "1." — FM strips the trailing
       -- zero and leaves the bare point. '0' after the point forces the digit.
       CASE
         WHEN n.data_amount_mb >= 1024 AND (n.data_amount_mb % 1024) = 0
           THEN (n.data_amount_mb / 1024)::text || ' GB'
         WHEN n.data_amount_mb >= 1024
           THEN to_char(n.data_amount_mb / 1024.0, 'FM999990.0') || ' GB'
         ELSE n.data_amount_mb::text || ' MB'
       END || ' for ' || n.duration_days || ' days at $'
         || to_char(n.retail_usd, 'FM99999990.00')
FROM esim_now n
JOIN esim_base b ON b.country_code = n.country_code
WHERE b.usd_per_gb > 0;
$function$;

REVOKE ALL ON FUNCTION public.offer_watch_metrics(integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.offer_watch_metrics(integer) TO service_role;


-- ---------------------------------------------------------------------------
-- 7. sync_auto_price_watches() — keep origin='auto' watches in step with the
--    user's active SIM lines.
--
-- The carrier code must be resolved exactly the way worker_offers_cache.js
-- picks it when it fills the cache (dt_carrier for a dtone carrier, zen_carrier
-- otherwise) or the watch would never match a cached offer.
--
-- Retirement is a DELETE, including of rows the user switched off. The
-- alternative — keeping disabled rows forever — leaves ghosts in the UI for
-- lines that no longer exist. The consequence is that re-adding a deleted line
-- brings its watch back enabled, which is why the app offers a SWITCH rather
-- than a delete button on auto rows: turning one off is durable for as long as
-- the line exists, which is as long as the row means anything.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sync_auto_price_watches()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_added   integer;
  v_removed integer;
BEGIN
  WITH live AS (
    SELECT DISTINCT
           sl.user_id,
           co.iso_code AS country_code,
           CASE WHEN LOWER(COALESCE(ca.api_provider, 'zendit')) = 'dtone'
                THEN ca.dt_carrier ELSE ca.zen_carrier END AS carrier_code
    FROM public.sim_lines sl
    JOIN public.carriers  ca ON ca.id = sl.carrier_id
    JOIN public.countries co ON co.id = ca.country_id
    WHERE sl.status = 'active'
  )
  INSERT INTO public.offer_price_watches (user_id, source, country_code, carrier_code, origin)
  SELECT l.user_id, 'topup', l.country_code, l.carrier_code, 'auto'
  FROM live l
  WHERE l.carrier_code IS NOT NULL AND l.country_code IS NOT NULL
  ON CONFLICT DO NOTHING;

  GET DIAGNOSTICS v_added = ROW_COUNT;

  WITH live AS (
    SELECT DISTINCT
           sl.user_id,
           co.iso_code AS country_code,
           CASE WHEN LOWER(COALESCE(ca.api_provider, 'zendit')) = 'dtone'
                THEN ca.dt_carrier ELSE ca.zen_carrier END AS carrier_code
    FROM public.sim_lines sl
    JOIN public.carriers  ca ON ca.id = sl.carrier_id
    JOIN public.countries co ON co.id = ca.country_id
    WHERE sl.status = 'active'
  )
  DELETE FROM public.offer_price_watches w
  WHERE w.origin = 'auto'
    AND NOT EXISTS (
      SELECT 1 FROM live l
      WHERE l.user_id = w.user_id
        AND l.country_code = w.country_code
        AND l.carrier_code = w.carrier_code
    );

  GET DIAGNOSTICS v_removed = ROW_COUNT;

  RETURN v_added + v_removed;
END;
$function$;

REVOKE ALL ON FUNCTION public.sync_auto_price_watches() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sync_auto_price_watches() TO service_role;


-- ---------------------------------------------------------------------------
-- 8. detect_offer_price_drops() — refresh every watch, then alert on the ones
--    that moved far enough.
--
-- Four independent suppressions, all deliberate:
--   * no explicit promo consent  -> nothing is written at all (see header note 4);
--   * a suspended user gets no marketing;
--   * cooldown, so a price sliding down over a week is one alert, not seven;
--   * the price must beat the one we last announced, so the cooldown expiring
--     does not re-announce yesterday's news.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.detect_offer_price_drops()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_baseline_days integer;
  v_cooldown_days integer;
  v_default_thr   numeric;
  v_count         integer := 0;
  v_place         text;
  r               RECORD;
BEGIN
  SELECT COALESCE(NULLIF(config_value, '')::integer, 30) INTO v_baseline_days
  FROM public.system_configs WHERE config_key = 'PRICE_WATCH_BASELINE_DAYS';
  v_baseline_days := COALESCE(v_baseline_days, 30);

  SELECT COALESCE(NULLIF(config_value, '')::integer, 7) INTO v_cooldown_days
  FROM public.system_configs WHERE config_key = 'PRICE_WATCH_COOLDOWN_DAYS';
  v_cooldown_days := COALESCE(v_cooldown_days, 7);

  SELECT COALESCE(NULLIF(config_value, '')::numeric, 10) INTO v_default_thr
  FROM public.system_configs WHERE config_key = 'PRICE_DROP_THRESHOLD_PERCENT';
  v_default_thr := COALESCE(v_default_thr, 10);

  -- Everything the app shows, refreshed whether or not it alerts.
  UPDATE public.offer_price_watches w
     SET last_best_usd     = m.current_metric,
         last_baseline_usd = m.baseline_metric,
         last_checked_at   = NOW()
    FROM public.offer_watch_metrics(v_baseline_days) m
   WHERE w.is_active
     AND m.source = w.source
     AND m.country_code = w.country_code
     AND COALESCE(m.carrier_code, '') = COALESCE(w.carrier_code, '');

  FOR r IN
    SELECT w.id,
           w.user_id,
           w.source,
           w.country_code,
           w.carrier_code,
           m.current_metric,
           m.baseline_metric,
           m.drop_percent,
           m.offer_label,
           co.name       AS country_name,
           co.flag_emoji AS flag
    FROM public.offer_price_watches w
    JOIN public.offer_watch_metrics(v_baseline_days) m
      ON m.source = w.source
     AND m.country_code = w.country_code
     AND COALESCE(m.carrier_code, '') = COALESCE(w.carrier_code, '')
    LEFT JOIN public.countries co ON co.iso_code = w.country_code
    WHERE w.is_active
      AND m.drop_percent IS NOT NULL
      AND m.drop_percent >= COALESCE(w.threshold_percent, v_default_thr)
      AND (w.last_alert_at IS NULL
           OR w.last_alert_at < NOW() - (v_cooldown_days || ' days')::interval)
      AND (w.last_alerted_best_usd IS NULL
           OR m.current_metric < w.last_alerted_best_usd)
      AND EXISTS (
        SELECT 1 FROM public.alert_settings a
        WHERE a.user_id = w.user_id
          AND a.category = 'promo'
          AND a.is_enabled = true
      )
      AND NOT COALESCE(
        (SELECT p.is_suspended FROM public.profiles p WHERE p.id = w.user_id), false)
  LOOP
    v_place := COALESCE(NULLIF(r.country_name, ''), r.country_code);

    INSERT INTO public.notifications (
      user_id, category, title, body, action_url, sim_line_id, is_read, created_at
    ) VALUES (
      r.user_id,
      'promo',
      CASE r.source
        WHEN 'esim' THEN 'eSIM data for ' || v_place || ' just got cheaper'
        ELSE r.carrier_code || ' top-ups in ' || v_place || ' just got cheaper'
      END,
      CASE r.source
        WHEN 'esim' THEN
          'Best price for ' || v_place || ' is now $'
            || to_char(r.current_metric, 'FM99999990.00') || '/GB, down '
            || to_char(r.drop_percent, 'FM990.0') || '% from $'
            || to_char(r.baseline_metric, 'FM99999990.00') || '/GB. Cheapest right now: '
            || COALESCE(r.offer_label, 'see the eSIM store') || '.'
        ELSE
          COALESCE(r.offer_label, 'A top-up you watch is cheaper') || ' — '
            || to_char(r.drop_percent, 'FM990.0') || '% less than '
            || v_baseline_days || ' days ago.'
      END,
      CASE r.source WHEN 'esim' THEN '/esim/plans' ELSE '/esim/price-watch' END,
      NULL,
      false,
      NOW()
    );

    UPDATE public.offer_price_watches
       SET last_alert_at         = NOW(),
           last_alerted_best_usd = r.current_metric
     WHERE id = r.id;

    v_count := v_count + 1;
  END LOOP;

  RETURN v_count;
END;
$function$;

REVOKE ALL ON FUNCTION public.detect_offer_price_drops() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.detect_offer_price_drops() TO service_role;


-- ---------------------------------------------------------------------------
-- 9. prune_offer_price_history() — retention, without ever orphaning an offer.
--
-- The NOT-the-newest condition matters: deleting an offer's only row would
-- destroy its baseline and silently stop it being watchable.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.prune_offer_price_history()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_days integer;
  v_rows integer;
BEGIN
  SELECT COALESCE(NULLIF(config_value, '')::integer, 180) INTO v_days
  FROM public.system_configs WHERE config_key = 'PRICE_HISTORY_RETENTION_DAYS';
  v_days := COALESCE(v_days, 180);

  DELETE FROM public.offer_price_history h
  WHERE h.recorded_at < NOW() - (v_days || ' days')::interval
    AND EXISTS (
      SELECT 1 FROM public.offer_price_history n
      WHERE n.source = h.source
        AND n.offer_key = h.offer_key
        AND n.recorded_at > h.recorded_at
    );

  GET DIAGNOSTICS v_rows = ROW_COUNT;
  RETURN v_rows;
END;
$function$;

REVOKE ALL ON FUNCTION public.prune_offer_price_history() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.prune_offer_price_history() TO service_role;


-- ---------------------------------------------------------------------------
-- 10. refresh_offer_price_watch() — the single cron entry point.
--
-- No WHEN OTHERS handler, for the reason G1 spelled out: enforce_rate_limit
-- ends in one and it silently swallowed a new guard during F0. A nightly job
-- that fails must surface in cron.job_run_details.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.refresh_offer_price_watch()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_synced integer;
  v_alerts integer;
  v_pruned integer;
BEGIN
  v_synced := public.sync_auto_price_watches();
  v_alerts := public.detect_offer_price_drops();
  v_pruned := public.prune_offer_price_history();

  RETURN jsonb_build_object(
    'watches_synced', v_synced,
    'alerts',         v_alerts,
    'history_pruned', v_pruned,
    'ran_at',         NOW()
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.refresh_offer_price_watch() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.refresh_offer_price_watch() TO service_role;


-- ---------------------------------------------------------------------------
-- 11. Nightly at 02:40 UTC — after G1's forecast run at 02:20, clear of the
--     03:00 rate-limit prune.
-- ---------------------------------------------------------------------------
DO $cron$
BEGIN
  PERFORM cron.unschedule('refresh-offer-price-watch')
  WHERE EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'refresh-offer-price-watch');

  PERFORM cron.schedule(
    'refresh-offer-price-watch',
    '40 2 * * *',
    'SELECT public.refresh_offer_price_watch();'
  );
END;
$cron$;
