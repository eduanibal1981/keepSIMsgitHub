-- ============================================================================
-- G2 — Price-drop / best-offer watch
--
-- Feature suggestion #2 in doc/PRODUCTION_PLAN_REVIEW.md § 6. The catalogs
-- (`provider_offers_cache`, 783 top-up offers, refreshed every 10 minutes;
-- `esim_offers_cache`, 50 bundles, every 6 hours) are overwritten in place and
-- history is kept nowhere, so the product cannot answer "is this cheaper than
-- it was?" — the single most useful question a refill app can answer.
--
-- This adds the history, a per-user watch list, and a nightly `promo`-category
-- notification when a watched subject's best price drops by more than a
-- configurable percentage.
--
-- ── Four deliberate departures from the sketch in the review ────────────────
--
-- 1. HISTORY IS WRITTEN BY TRIGGERS, NOT BY THE TWO WORKERS. The sketch says
--    "written by the two catalog workers", but both workers live on the
--    owner-gated VM (doc/PROJECT_TOPOLOGY.md § 5), so a worker change cannot
--    ship from here — the same wall G1 hit with the eSIM usage poll. A row
--    trigger on each cache table captures every write regardless of who made
--    it (worker, Edge Function, dashboard), needs no deploy, and cannot drift
--    out of sync with the worker code. The UPDATE triggers carry a WHEN clause
--    on the price columns, so the 10-minute refresh — which rewrites
--    `refreshed_at` on all 783 rows every cycle — appends nothing unless a
--    price actually moved.
--
-- 2. "$/GB" IS ONLY MEANINGFUL FOR ONE OF THE TWO CATALOGS. eSIM bundles carry
--    `data_amount_mb`, so best $/GB per country is well defined and is exactly
--    what the review asks for. Top-ups do not: `provider_offers_cache` holds
--    airtime denominations with no data amount at all (and `send_min`/`send_max`
--    are NULL for every FIXED offer, so there is not even a local face value to
--    divide by). Inventing a $/GB there would be a fabricated number. Top-ups
--    are therefore tracked PER OFFER — "the $10.00 Zong bundle now costs $8.80"
--    — which is the honest comparable and, unlike a country-level minimum, does
--    not fire merely because a cheaper denomination appeared.
--    `offer_watch_metrics.metric_kind` says which of the two a row is.
--
-- 3. WATCHES ARE SEEDED FROM THE USER'S OWN SIM LINES. A watchlist nobody fills
--    in is worth nothing; on the live database that would be 0 rows against 10
--    active lines. `sync_auto_price_watches()` keeps one `origin = 'auto'` watch
--    per (country, carrier) the user actually holds a line on. The user can
--    switch any of them off, and eSIM watches stay explicit — a destination the
--    user browsed is a real signal, a destination they already bought is not.
--
-- 4. CONSENT IS CHECKED BEFORE THE ROW IS WRITTEN, NOT ONLY BEFORE DISPATCH.
--    `trg_fn_dispatch_notification` already gates promo fan-out on explicit
--    opt-in (C2), so push/email compliance is genuinely done. But it still
--    writes the `notifications` row, which would put marketing in the in-app
--    list of users who never consented. `detect_offer_price_drops()` requires
--    an enabled `alert_settings` row for `promo` before inserting anything.
--
-- Nothing here is callable by anon or authenticated: every function is
-- cron-driven and service_role-only. The app reads `offer_price_watches` as a
-- plain RLS-guarded table and writes only two columns of it.
--
-- ⚠️ MARKUP ISOLATION. `esim_offers_cache.wholesale_price_usd` is deliberately
-- unreadable by clients — the `esim_offers` view exists solely to expose retail
-- (doc/RLS_MATRIX.md). `offer_price_history` stores the same wholesale numbers
-- and is therefore deny-all, exactly like `esim_usage_samples`. Every number
-- that reaches a client — `offer_price_watches.last_best_usd`, the notification
-- body — has ESIM_MARKUP_PERCENT already applied.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. offer_price_history — append-only price log for both catalogs.
--    Internal telemetry: deny-all (RLS on, zero policies), like
--    esim_usage_samples and offline_refill_events. It holds wholesale eSIM
--    prices; see the markup note above.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.offer_price_history (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source         text        NOT NULL CHECK (source IN ('topup','esim')),
  -- topup: api_provider || '|' || offer_id ;  esim: provider || '|' || bundle_name
  offer_key      text        NOT NULL,
  country_code   text,        -- topup only (a bundle covers many countries)
  carrier_code   text,        -- topup only
  countries      text[],      -- esim only
  data_amount_mb bigint,      -- esim only
  duration_days  integer,     -- esim only
  -- topup: the price the user pays. esim: WHOLESALE, never expose it raw.
  price_usd      numeric(12,4) NOT NULL,
  recorded_at    timestamptz NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS offer_price_history_key_time_idx
  ON public.offer_price_history (source, offer_key, recorded_at DESC);
CREATE INDEX IF NOT EXISTS offer_price_history_time_idx
  ON public.offer_price_history (recorded_at);

ALTER TABLE public.offer_price_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.offer_price_history FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.offer_price_history TO service_role;
-- No sequence grant: an identity column derives its privilege from the table.

COMMENT ON TABLE public.offer_price_history IS
  'G2: append-only price log for provider_offers_cache and esim_offers_cache, written by AFTER triggers on those tables. Deny-all by design (RLS on, zero policies) — it holds wholesale eSIM prices.';


-- ---------------------------------------------------------------------------
-- 2. The triggers that fill it.
--
-- One AFTER INSERT (no OLD to compare against) and one AFTER UPDATE with a
-- WHEN clause, per table. The WHEN clause is the whole point: the offers worker
-- upserts all 783 rows every 10 minutes and only `refreshed_at` changes, so
-- without it this table would gain ~113k rows a day of pure noise.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_fn_record_topup_price_history()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_price numeric;
BEGIN
  -- FIXED offers carry price_fixed_usd; RANGE offers are tracked at their entry
  -- price (price_min_usd), which is the number the user sees first.
  v_price := COALESCE(NEW.price_fixed_usd, NEW.price_min_usd);
  IF v_price IS NULL OR v_price <= 0 THEN
    RETURN NULL;
  END IF;

  INSERT INTO public.offer_price_history
    (source, offer_key, country_code, carrier_code, price_usd)
  VALUES
    ('topup', NEW.api_provider || '|' || NEW.offer_id,
     NEW.country_code, NEW.carrier_code, v_price);

  RETURN NULL;
END;
$function$;

CREATE OR REPLACE FUNCTION public.trg_fn_record_esim_price_history()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NEW.wholesale_price_usd IS NULL OR NEW.wholesale_price_usd <= 0 THEN
    RETURN NULL;
  END IF;

  INSERT INTO public.offer_price_history
    (source, offer_key, countries, data_amount_mb, duration_days, price_usd)
  VALUES
    ('esim', NEW.provider || '|' || NEW.bundle_name,
     NEW.countries, NEW.data_amount_mb, NEW.duration_days, NEW.wholesale_price_usd);

  RETURN NULL;
END;
$function$;

REVOKE ALL ON FUNCTION public.trg_fn_record_topup_price_history() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_fn_record_esim_price_history()  FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_provider_offers_price_history_ins ON public.provider_offers_cache;
CREATE TRIGGER trg_provider_offers_price_history_ins
  AFTER INSERT ON public.provider_offers_cache
  FOR EACH ROW EXECUTE FUNCTION public.trg_fn_record_topup_price_history();

DROP TRIGGER IF EXISTS trg_provider_offers_price_history_upd ON public.provider_offers_cache;
CREATE TRIGGER trg_provider_offers_price_history_upd
  AFTER UPDATE ON public.provider_offers_cache
  FOR EACH ROW
  WHEN (OLD.price_fixed_usd IS DISTINCT FROM NEW.price_fixed_usd
     OR OLD.price_min_usd   IS DISTINCT FROM NEW.price_min_usd
     OR OLD.price_max_usd   IS DISTINCT FROM NEW.price_max_usd)
  EXECUTE FUNCTION public.trg_fn_record_topup_price_history();

DROP TRIGGER IF EXISTS trg_esim_offers_price_history_ins ON public.esim_offers_cache;
CREATE TRIGGER trg_esim_offers_price_history_ins
  AFTER INSERT ON public.esim_offers_cache
  FOR EACH ROW EXECUTE FUNCTION public.trg_fn_record_esim_price_history();

DROP TRIGGER IF EXISTS trg_esim_offers_price_history_upd ON public.esim_offers_cache;
CREATE TRIGGER trg_esim_offers_price_history_upd
  AFTER UPDATE ON public.esim_offers_cache
  FOR EACH ROW
  WHEN (OLD.wholesale_price_usd IS DISTINCT FROM NEW.wholesale_price_usd
     OR OLD.data_amount_mb      IS DISTINCT FROM NEW.data_amount_mb
     OR OLD.duration_days       IS DISTINCT FROM NEW.duration_days)
  EXECUTE FUNCTION public.trg_fn_record_esim_price_history();


-- ---------------------------------------------------------------------------
-- 3. Seed today's prices so a baseline exists from the first night.
--
-- Without this the feature would be inert until each offer happened to change
-- price once. Guarded by NOT EXISTS so the migration is re-runnable.
-- ---------------------------------------------------------------------------
INSERT INTO public.offer_price_history
  (source, offer_key, country_code, carrier_code, price_usd)
SELECT 'topup',
       p.api_provider || '|' || p.offer_id,
       p.country_code,
       p.carrier_code,
       COALESCE(p.price_fixed_usd, p.price_min_usd)
FROM public.provider_offers_cache p
WHERE COALESCE(p.price_fixed_usd, p.price_min_usd) > 0
  AND NOT EXISTS (
    SELECT 1 FROM public.offer_price_history h
    WHERE h.source = 'topup'
      AND h.offer_key = p.api_provider || '|' || p.offer_id
  );

INSERT INTO public.offer_price_history
  (source, offer_key, countries, data_amount_mb, duration_days, price_usd)
SELECT 'esim',
       c.provider || '|' || c.bundle_name,
       c.countries,
       c.data_amount_mb,
       c.duration_days,
       c.wholesale_price_usd
FROM public.esim_offers_cache c
WHERE c.wholesale_price_usd > 0
  AND NOT EXISTS (
    SELECT 1 FROM public.offer_price_history h
    WHERE h.source = 'esim'
      AND h.offer_key = c.provider || '|' || c.bundle_name
  );


-- ---------------------------------------------------------------------------
-- 4. offer_price_watches — one row per (user, subject) being watched.
--
--    source = 'topup' -> subject is (country_code, carrier_code)
--    source = 'esim'  -> subject is (country_code)
--
-- The client owns exactly two columns: is_active and threshold_percent.
-- Everything else is bookkeeping written by the nightly job, and `origin` is
-- server-owned so a client cannot forge an 'auto' row that
-- sync_auto_price_watches() would then manage.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.offer_price_watches (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id               uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  source                text NOT NULL CHECK (source IN ('topup','esim')),
  country_code          text NOT NULL,
  carrier_code          text,
  origin                text NOT NULL DEFAULT 'user' CHECK (origin IN ('user','auto')),
  is_active             boolean NOT NULL DEFAULT true,

  -- NULL means "use PRICE_DROP_THRESHOLD_PERCENT", so the global default can be
  -- retuned without rewriting every row.
  threshold_percent     numeric(5,2)
    CHECK (threshold_percent IS NULL OR (threshold_percent >= 1 AND threshold_percent <= 90)),

  -- Client-visible, and therefore RETAIL for eSIM ($/GB) — never wholesale.
  last_best_usd         numeric(12,4),
  last_baseline_usd     numeric(12,4),
  last_alerted_best_usd numeric(12,4),
  last_alert_at         timestamptz,
  last_checked_at       timestamptz,

  created_at            timestamptz NOT NULL DEFAULT NOW(),
  updated_at            timestamptz NOT NULL DEFAULT NOW(),

  CONSTRAINT offer_price_watches_carrier_matches_source CHECK (
    (source = 'topup' AND carrier_code IS NOT NULL) OR
    (source = 'esim'  AND carrier_code IS NULL)
  )
);

-- Expression index: carrier_code is NULL for every eSIM watch, and NULLs do not
-- collide in a plain unique index, so a user could otherwise stack duplicates.
CREATE UNIQUE INDEX IF NOT EXISTS offer_price_watches_subject_uq
  ON public.offer_price_watches (user_id, source, country_code, COALESCE(carrier_code, ''));
CREATE INDEX IF NOT EXISTS offer_price_watches_user_idx
  ON public.offer_price_watches (user_id);
CREATE INDEX IF NOT EXISTS offer_price_watches_active_idx
  ON public.offer_price_watches (source, country_code) WHERE is_active;

ALTER TABLE public.offer_price_watches ENABLE ROW LEVEL SECURITY;

