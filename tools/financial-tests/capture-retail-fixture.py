"""Capture Task 19's data-free SQL extension from an operator-supplied schema dump.

Usage: python3 tools/financial-tests/capture-retail-fixture.py /path/to/live_public_schema.sql
Load after the financial bootstrap and pricing_contract_baseline.sql. Function
bodies must match the independently captured October 16 catalogue hashes.
"""
from pathlib import Path
import hashlib
import json
import re
import sys
ROOT=Path(__file__).resolve().parents[2]
dump=Path(sys.argv[1]).read_text()
catalog=json.loads((ROOT/'docs/reviews/migration-cleanup-20261016/live-catalog.json').read_text())
tables=['supplier_policy','refill_approval_quotes']
functions=['list_carrier_offers','list_refill_offers','pick_best_refill_offer',
 'choose_supplier_for_offer','supplier_candidates','supplier_effective_cost',
 'resolve_household_payer','household_spend_check','household_spend_mtd',
 'request_instant_refill','config_numeric','interpolate_offer_value','assert_admin']
views=['carrier_supplier_routing','provider_offers_effective','zendit_offers_cache','esim_offers']
parts=['''-- ISOLATED ONLY: Task 19 data-free schema extension from the supplied export.
-- Generated by tools/financial-tests/capture-retail-fixture.py.
SET check_function_bodies=false;
-- Replace the financial fixture's narrow household adapter with the real body.
DROP FUNCTION public.household_spend_check(uuid,uuid,numeric,uuid);''']
for name in tables:
 match=re.search(r'CREATE TABLE IF NOT EXISTS "public"\."'+name+r'" \(.*?\n\);',dump,re.S)
 if not match:raise ValueError('Missing table '+name)
 parts.append(match[0])
for prefix in ['PRIMARY KEY','UNIQUE','FOREIGN KEY']:
 for c in catalog['constraints']:
  if c['table'] in tables and c['definition'].startswith(prefix):
   parts.append(f'ALTER TABLE public."{c["table"]}" ADD CONSTRAINT "{c["name"]}" {c["definition"]};')
for name in views:
 match=re.search(r'CREATE OR REPLACE VIEW "public"\."'+name+r'".*?;',dump,re.S)
 if not match:raise ValueError('Missing view '+name)
 parts.append(match[0])
hashes={}
for name in functions:
 match=re.search(r'CREATE OR REPLACE FUNCTION "public"\."'+name+r'"\(.*?\n    AS (\$[^$]*\$)(.*?)\1;',dump,re.S)
 if not match:raise ValueError('Missing function '+name)
 expected=next(f for f in catalog['functions'] if f['name']==name)
 digest=hashlib.sha256(match[2].encode()).hexdigest()
 if digest!=expected['source_sha256']:raise ValueError('Catalogue body mismatch '+name)
 hashes[name]=digest;parts.append(match[0])
for name in tables+['provider_offers_cache','esim_orders']+views:
 if name not in views:
  relation=next(r for r in catalog['relations'] if r['name']==name)
  if relation['rls']:parts.append(f'ALTER TABLE public.{name} ENABLE ROW LEVEL SECURITY;')
  parts.extend(re.findall(r'CREATE POLICY [^\n]* ON "public"\."'+name+r'"[^\n]*;',dump))
 parts.extend(re.findall(r'GRANT [^\n]* ON TABLE "public"\."'+name+r'"[^\n]*;',dump))
parts.append('SET check_function_bodies=true;')
output=ROOT/'supabase/tests/fixtures/retail_ownership_baseline.sql'
output.write_text('\n\n'.join(parts)+'\n')
output.with_suffix('.json').write_text(json.dumps(dict(tables=tables,views=views,functions=hashes,
 requires=['financial_remediation_baseline.sql','financial_production_snapshot.json','pricing_contract_baseline.sql'],
 limits='Bounded catalogue/ownership extension. Real public constraints, supplier/household functions and supplemental API grants/RLS. Auth, risk/rate limiting, notification/health and provider/network adapters remain those of the isolated financial harness. No complete Supabase/PostgREST/Realtime/provider or production parity claim.'),indent=2)+'\n')
print(f'Captured {len(tables)} tables, {len(views)} views and {len(functions)} hash-verified functions')
