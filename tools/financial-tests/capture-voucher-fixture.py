"""Capture data-free Task 21 contracts from the supplied public schema export.

Usage: python3 tools/financial-tests/capture-voucher-fixture.py /path/to/schema.sql
Load after bootstrapProductionBaseline; no production connection is made.
"""
from pathlib import Path
import hashlib
import json
import re
import sys

root = Path(__file__).resolve().parents[2]
dump = Path(sys.argv[1]).read_text()
catalog = json.loads((root / 'docs/reviews/migration-cleanup-20261016/live-catalog.json').read_text())
tables = ['offline_voucher_requests', 'offline_voucher_grants',
          'offline_voucher_stock', 'carrier_voucher_redemption']
functions = ['offline_voucher_state', 'admin_list_voucher_requests']
parts = ['-- ISOLATED ONLY: Task 21 extension. Generated by capture-voucher-fixture.py.',
         'SET check_function_bodies=false;']
for name in tables:
    parts.append(re.search(r'CREATE TABLE IF NOT EXISTS "public"\."' + name + r'" \(.*?\n\);', dump, re.S)[0])
constraints = [c for c in catalog['constraints'] if c['table'] in tables]
for kind in ['PRIMARY KEY', 'UNIQUE', 'FOREIGN KEY']:
    for c in constraints:
        if c['definition'].startswith(kind):
            parts.append(f'ALTER TABLE public."{c["table"]}" ADD CONSTRAINT "{c["name"]}" {c["definition"]};')
for index in catalog['indexes']:
    if index['table'] in tables and not any(c['name'] == index['name'] for c in constraints):
        parts.append(index['definition'] + ';')
for name in tables:
    relation = next(r for r in catalog['relations'] if r['name'] == name)
    if relation['rls']:
        parts.append(f'ALTER TABLE public.{name} ENABLE ROW LEVEL SECURITY;')
    parts.extend(re.findall(r'CREATE POLICY [^\n]* ON "public"\."' + name + r'"[^\n]*;', dump))
    parts.extend(re.findall(r'GRANT [^\n]* ON TABLE "public"\."' + name + r'"[^\n]*;', dump))
hashes = {}
for name in functions:
    match = re.search(r'CREATE OR REPLACE FUNCTION "public"\."' + name + r'"\(.*?\n    AS (\$[^$]*\$)(.*?)\1;', dump, re.S)
    expected = next(f for f in catalog['functions'] if f['name'] == name)
    digest = hashlib.sha256(match[2].encode()).hexdigest()
    if digest != expected['source_sha256']:
        raise ValueError('Catalogue body mismatch: ' + name)
    hashes[name] = digest
    parts.append(match[0])
    signature = f'public.{name}({expected["types"]})'
    parts.append(f'REVOKE ALL ON FUNCTION {signature} FROM PUBLIC,anon,authenticated,service_role;')
    for role in ['anon', 'authenticated', 'service_role']:
        if re.search(r'(?:\{|,)' + role + r'=X', expected['acl'] or ''):
            parts.append(f'GRANT EXECUTE ON FUNCTION {signature} TO {role};')
parts.append('SET check_function_bodies=true;')
output = root / 'supabase/tests/fixtures/offline_voucher_baseline.sql'
output.write_text('\n\n'.join(parts) + '\n')
output.with_suffix('.json').write_text(json.dumps(dict(tables=tables, functions=hashes,
    requires='bootstrapProductionBaseline',
    limits='Data-free production-shaped extension, including all captured constraints, indexes, table ACLs and RLS. Auth claims are isolated adapters; voucher mutation/crypto, triggers, Supabase API/cache and provider/recovery endpoint behavior are not exercised.'), indent=2) + '\n')
print('Captured four tables and two independently hash-verified functions')
