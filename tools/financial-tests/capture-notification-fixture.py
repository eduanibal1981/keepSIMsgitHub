"""Extract a bounded, data-free notification fixture from a public schema dump.

Usage: python3 tools/financial-tests/capture-notification-fixture.py /path/to/live_public_schema.sql
Add --forecasts to capture the forecast extension, loaded after the notification fixture.
Add --maintenance to capture the admin/deletion/email extension instead.
Function bodies must match the independently captured October 16 catalog hashes.
No database connection is made. Omitted foreign keys/triggers are recorded.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
catalog = json.loads((ROOT / 'docs/reviews/migration-cleanup-20261016/live-catalog.json').read_text())
dump = Path(sys.argv[1]).read_text()
tables = '''alert_settings notification_channel_catalog notification_channels
notification_dispatch_jobs notification_deliveries notification_channel_targets notifications
sim_line_alert_clock_states system_configs system_alerts countries carriers carrier_rules
sim_lines profiles topup_executions scheduled_topups wallets wallet_holds line_activity_log
user_preferences'''.split()
functions = '''emit_upcoming_refill_low_balance_reminders process_due_notifications
emit_missing_recharge_date_reminders emit_urgent_deactivation_alerts notification_channel_eligible
trg_fn_dispatch_notification trg_fn_notify_system_alert calculate_sim_line_alert_clock
sync_all_sim_line_alert_clocks claim_notification_dispatch_jobs finish_notification_dispatch_job
claim_notification_channel_target finish_notification_channel_target'''.split()
forecast_mode = '--forecasts' in sys.argv[2:]
maintenance_mode = '--maintenance' in sys.argv[2:]
dependency_tables = tables if forecast_mode or maintenance_mode else []
if forecast_mode:
    tables = 'user_esims esim_orders esim_offers_cache esim_usage_samples sim_line_usage_forecast household_members sim_line_rescue_policy'.split()
    functions = 'compute_usage_forecasts refresh_usage_forecasts snapshot_esim_usage emit_forecast_depletion_alerts refill_interval_days record_manual_external_recharge'.split()
if maintenance_mode:
    tables = 'account_deletions admin_audit_log security_logs wallet_funding_lots wallet_refund_requests wallet_transactions user_esims esim_orders admin_emails virtual_did_numbers call_records'.split()
    functions = 'admin_purge_user_account admin_prune_database_logs prune_database_logs check_rate_limit_health purge_deleted_accounts admin_log assert_admin is_power_user is_user_suspended get_internal_secret kick_admin_email admin_send_email delete_auth_user_by_id cancel_account_deletion'.split()
parts = ['''-- ISOLATED ONLY: data-free notification production contracts.
-- Generated by tools/financial-tests/capture-notification-fixture.py.
CREATE ROLE anon;
CREATE ROLE authenticated;
CREATE ROLE service_role BYPASSRLS;
CREATE SCHEMA auth;
CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
 SELECT (nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid
$$;''',
'''CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$
 SELECT nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'role'
$$;
GRANT USAGE ON SCHEMA public,auth TO anon,authenticated,service_role;
SET check_function_bodies=false;''']
if forecast_mode or maintenance_mode:
    parts = ['-- ISOLATED ONLY: '+('maintenance' if maintenance_mode else 'forecast')+' extension; load notification_scheduler_baseline.sql first.',
             'SET check_function_bodies=false;']
for name in tables:
    match = re.search(r'CREATE TABLE IF NOT EXISTS "public"\."' + name + r'" \(.*?\n\);', dump, re.S)
    if not match:
        raise ValueError('Missing table: ' + name)
    parts.append(match[0])

omitted = []
constraints = [c for c in catalog['constraints'] if c['table'] in tables]
for kind in ['p', 'u', 'c', 'f']:
    for c in constraints:
        prefix = {'p': 'PRIMARY KEY', 'u': 'UNIQUE', 'c': 'CHECK', 'f': 'FOREIGN KEY'}[kind]
        if not c['definition'].startswith(prefix):
            continue
        # CHECK constraints are already present in the unmodified dump table.
        if kind == 'c':
            continue
        if kind == 'f':
            target = re.search(r'REFERENCES ([\w.]+)', c['definition'])[1]
            if target not in tables + dependency_tables and target != 'auth.users':
                omitted.append(c)
                continue
        parts.append(f'ALTER TABLE public."{c["table"]}" ADD CONSTRAINT "{c["name"]}" {c["definition"]};')
for idx in catalog['indexes']:
    if idx['table'] in tables and not any(c['name'] == idx['name'] for c in constraints):
        parts.append(idx['definition'] + ';')

hashes = {}
for name in functions:
    match = re.search(r'CREATE OR REPLACE FUNCTION "public"\."' + name + r'"\(.*?\n    AS (\$[^$]*\$)(.*?)\1;', dump, re.S)
    if not match:
        raise ValueError('Missing function: ' + name)
    expected = next(f for f in catalog['functions'] if f['name'] == name)
    digest = hashlib.sha256(match[2].encode()).hexdigest()
    if digest != expected['source_sha256']:
        raise ValueError('Body differs from independently captured catalog: ' + name)
    hashes[name] = digest
    parts.append(match[0])
    signature = f'public."{name}"({expected["types"]})'
    parts.append(f'REVOKE ALL ON FUNCTION {signature} FROM PUBLIC,anon,authenticated,service_role;')
    for role in ['anon', 'authenticated', 'service_role']:
        if re.search(r'(?:\{|,)' + role + r'=X', expected['acl'] or ''):
            parts.append(f'GRANT EXECUTE ON FUNCTION {signature} TO {role};')

triggers = [] if forecast_mode or maintenance_mode else [('trg_on_notification_created', 'notifications', 'trg_fn_dispatch_notification'),
                                     ('trg_notify_system_alert', 'system_alerts', 'trg_fn_notify_system_alert')]
for trigger, table, fn in triggers:
    parts.append(f'CREATE TRIGGER {trigger} AFTER INSERT ON public.{table} FOR EACH ROW EXECUTE FUNCTION public.{fn}();')
parts.append('SET check_function_bodies=true;')
output = ROOT / ('supabase/tests/fixtures/admin_maintenance_baseline.sql' if maintenance_mode else 'supabase/tests/fixtures/usage_forecast_baseline.sql' if forecast_mode else 'supabase/tests/fixtures/notification_scheduler_baseline.sql')
output.write_text('\n\n'.join(parts) + '\n')
manifest = dict(tables=tables, functions=hashes, omitted_foreign_keys=omitted,
                included_triggers=[t[0] for t in triggers],
                limits='No Supabase Auth lifecycle, API table ACL/RLS parity, unrelated triggers, cron extension or external delivery. Scheduler executes the recorded postgres SQL entry point in isolated native PostgreSQL.')
if forecast_mode:
    manifest['requires_fixture'] = 'notification_scheduler_baseline.sql'
    manifest['limits'] += ' Manual recharge checks run with captured ownership/household SQL; health and rescue trigger chains remain omitted.'
if maintenance_mode:
    manifest['requires_fixture'] = 'notification_scheduler_baseline.sql'
    manifest['limits'] += ' Vault, pg_net and cron relations use isolated stand-ins. Auth Admin and Storage operations are exercised separately through synthetic adapters; no live deletion or mail occurs.'
output.with_suffix('.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'Captured {len(tables)} tables and {len(functions)} catalog-verified functions; omitted {len(omitted)} external foreign keys')
